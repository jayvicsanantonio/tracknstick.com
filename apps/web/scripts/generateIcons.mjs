// Draws the app icon, a ring around a check, in a light and a dark version, and writes every size the app ships.
// Run with `pnpm icons`; needs `rsvg-convert` (Homebrew: `brew install librsvg`) to rasterise the SVG.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const ICONS = path.resolve(import.meta.dirname, '../public/icons');

// The brand colours of the two themes, --color-brand-primary in
// src/styles/index.css: emerald from the dark theme, pink from the light.
const EMERALD = '#2cedac';
const PINK = '#e13d97';

// The two versions of the icon. The light one is the home-screen icon, which
// cannot follow the phone's theme; the favicon switches between them.
const LIGHT = {
  name: 'light',
  background: ['#ffffff', '#f6f5f6'],
  ring: PINK,
  check: EMERALD,
};
const DARK = {
  name: 'dark',
  background: ['#121a17', '#050807'],
  ring: EMERALD,
  check: PINK,
};

const COMMENT = `<!-- Track N' Stick app icon: a ring around a check, pink and emerald.
       Generated by scripts/generateIcons.mjs; edit the script, not this file. -->`;

/**
 * One version of the icon on a 512 unit canvas. `rounded` gives it rounded
 * corners with transparent edges, for places that show the icon as it is;
 * without it the background fills the square, for platforms that cut their
 * own shape (maskable icons, iOS). The ring and check stay inside the
 * maskable safe zone, a circle of radius 205 at the centre.
 */
function artwork(palette, { rounded }) {
  const background = `background-${palette.name}`;
  return `<defs>
    <radialGradient id="${background}" cx="0.5" cy="0.35" r="0.75">
      <stop offset="0" stop-color="${palette.background[0]}"/>
      <stop offset="1" stop-color="${palette.background[1]}"/>
    </radialGradient>
  </defs>
  <rect width="512" height="512"${rounded ? ' rx="114"' : ''} fill="url(#${background})"/>
  <circle cx="256" cy="256" r="150" fill="none" stroke="${palette.ring}" stroke-width="40"/>
  <path d="M186 262L234 310L330 210" fill="none" stroke="${palette.check}" stroke-width="46" stroke-linecap="round" stroke-linejoin="round"/>`;
}

function iconSvg(palette, { rounded }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  ${COMMENT}
  ${artwork(palette, { rounded })}
</svg>
`;
}

/** Both versions in one SVG, showing the one that matches the colour scheme. */
function faviconSvg() {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  ${COMMENT}
  <style>
    .dark { display: none; }
    @media (prefers-color-scheme: dark) {
      .light { display: none; }
      .dark { display: inline; }
    }
  </style>
  <g class="light">
  ${artwork(LIGHT, { rounded: true })}
  </g>
  <g class="dark">
  ${artwork(DARK, { rounded: true })}
  </g>
</svg>
`;
}

function png(svg, size) {
  return execFileSync('rsvg-convert', ['-w', size, '-h', size], {
    input: svg,
  });
}

/** An .ico file holding the given PNG images, which the format allows. */
function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(1, 2); // image type: icon
  header.writeUInt16LE(images.length, 4);
  let offset = 6 + images.length * 16;
  const entries = images.map(({ size, data }) => {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size % 256, 0); // width; 0 means 256
    entry.writeUInt8(size % 256, 1); // height
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(data.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += data.length;
    return entry;
  });
  return Buffer.concat([header, ...entries, ...images.map((i) => i.data)]);
}

// The PNG and .ico icons are fixed images, so they are the light version.
const rounded = iconSvg(LIGHT, { rounded: true });
const fullBleed = iconSvg(LIGHT, { rounded: false });

const files = {
  'favicon.svg': faviconSvg(),
  'favicon-96x96.png': png(rounded, 96),
  'icon-192x192.png': png(rounded, 192),
  'icon-512x512.png': png(rounded, 512),
  'maskable-192x192.png': png(fullBleed, 192),
  'maskable-512x512.png': png(fullBleed, 512),
  'apple-touch-icon.png': png(fullBleed, 180),
  'favicon.ico': ico(
    [16, 32, 48].map((size) => ({ size, data: png(rounded, size) })),
  ),
};

for (const [name, contents] of Object.entries(files)) {
  writeFileSync(path.join(ICONS, name), contents);
  console.log(`wrote public/icons/${name}`);
}
