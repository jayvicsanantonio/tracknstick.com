// Draws the app icon, the Daily Tracker's completed pink progress ring and check on a flat dark emerald, and writes every size the app ships.
// Run with `pnpm icons`; needs `rsvg-convert` (Homebrew: `brew install librsvg`) to rasterise the SVG.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';

const ICONS = path.resolve(import.meta.dirname, '../public/icons');

// One flat dark emerald fills the background. The pale pink dial stands at
// 3:1 contrast or more against it.
const EMERALD = '#064d34';

// The light theme's brand colours from src/styles/index.css, as hex.
const BRAND_PRIMARY = '#e13d97'; // --color-brand-primary
const BRAND_SECONDARY = '#d8137f'; // --color-brand-secondary
const BRAND_TEXT_LIGHT = '#e869af'; // --color-brand-text-light

// The Daily Tracker's dial washes --color-brand-primary over the light
// theme's --color-background; these are those washes worked out as opaque
// colours, so the dial looks the same on the emerald.
const DIAL_CENTRE = '#fbe4f0';
const DIAL_EDGE = '#fadded';
const DIAL_HAIRLINE = '#f4b7d8';

// The medallion is drawn in the Daily Tracker's 200 unit ring space and
// scaled up so the ring's outer edge sits 171 units from the centre, well
// inside the maskable safe zone, a circle of radius 205.
const MEDALLION_SCALE = 1.9;

const COMMENT = `<!-- Track N' Stick app icon: the Daily Tracker's completed pink progress ring and check, on a flat dark emerald.
       Generated by scripts/generateIcons.mjs; edit the script, not this file. -->`;

/**
 * The icon on a 512 unit canvas. `rounded` gives it rounded
 * corners with transparent edges, for places that show the icon as it is;
 * their radius, 114 units, is the 22.37% of the width that iOS rounds app
 * icons by. Without it the background fills the square, for platforms that
 * cut their own shape (maskable icons, iOS).
 *
 * The ring, dial and check copy DailyHabitProgressIndicator once every habit
 * is done, in the light theme: a ring of radius 83 and width 14.5 in a 200
 * unit space, a dial of radius 67 with a hairline edge, and the 64 unit check
 * drawn at half the ring's size in its centre.
 */
function iconSvg({ rounded }) {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  ${COMMENT}
  <defs>
    <linearGradient id="ring" gradientUnits="userSpaceOnUse" x1="18" y1="18" x2="182" y2="182">
      <stop offset="0" stop-color="${BRAND_TEXT_LIGHT}"/>
      <stop offset="0.48" stop-color="${BRAND_PRIMARY}"/>
      <stop offset="1" stop-color="${BRAND_SECONDARY}"/>
    </linearGradient>
    <radialGradient id="dial" cx="0.5" cy="0.42" r="0.6">
      <stop offset="0" stop-color="${DIAL_CENTRE}"/>
      <stop offset="1" stop-color="${DIAL_EDGE}"/>
    </radialGradient>
    <linearGradient id="check" gradientUnits="userSpaceOnUse" x1="10" y1="49" x2="54" y2="17">
      <stop offset="0" stop-color="${BRAND_PRIMARY}"/>
      <stop offset="0.65" stop-color="${BRAND_PRIMARY}"/>
      <stop offset="1" stop-color="${BRAND_TEXT_LIGHT}"/>
    </linearGradient>
  </defs>
  <rect width="512" height="512"${rounded ? ' rx="114"' : ''} fill="${EMERALD}"/>
  <g transform="translate(256 256) scale(${MEDALLION_SCALE}) translate(-100 -100)">
    <circle cx="100" cy="100" r="67" fill="url(#dial)"/>
    <circle cx="100" cy="100" r="67" fill="none" stroke="${DIAL_HAIRLINE}" stroke-width="0.85"/>
    <circle cx="100" cy="100" r="83" fill="none" stroke="url(#ring)" stroke-width="14.5"/>
    <g transform="translate(50 50) scale(1.5625)">
      <path d="M10 34L25 49L54 17" fill="none" stroke="url(#check)" stroke-width="8.5" stroke-linecap="round" stroke-linejoin="round"/>
    </g>
  </g>
</svg>
`;
}

function png(svg, size) {
  return execFileSync('rsvg-convert', ['-w', size, '-h', size], {
    input: svg,
  });
}

/** An .ico file holding the given PNG images, which the format allows. */
function ico(images) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(1, 2); // image type: icon
  header.writeUInt16LE(images.length, 4);
  let offset = 6 + images.length * 16;
  const entries = images.map(({ size, data }) => {
    const entry = Buffer.alloc(16);
    entry.writeUInt8(size % 256, 0); // width; 0 means 256
    entry.writeUInt8(size % 256, 1); // height
    entry.writeUInt16LE(1, 4); // colour planes
    entry.writeUInt16LE(32, 6); // bits per pixel
    entry.writeUInt32LE(data.length, 8);
    entry.writeUInt32LE(offset, 12);
    offset += data.length;
    return entry;
  });
  return Buffer.concat([header, ...entries, ...images.map((i) => i.data)]);
}

const rounded = iconSvg({ rounded: true });
const fullBleed = iconSvg({ rounded: false });

const files = {
  'favicon.svg': rounded,
  'favicon-96x96.png': png(rounded, 96),
  'icon-192x192.png': png(rounded, 192),
  'icon-512x512.png': png(rounded, 512),
  'maskable-192x192.png': png(fullBleed, 192),
  'maskable-512x512.png': png(fullBleed, 512),
  'apple-touch-icon.png': png(fullBleed, 180),
  'favicon.ico': ico(
    [16, 32, 48].map((size) => ({ size, data: png(rounded, size) })),
  ),
};

for (const [name, contents] of Object.entries(files)) {
  writeFileSync(path.join(ICONS, name), contents);
  console.log(`wrote public/icons/${name}`);
}
